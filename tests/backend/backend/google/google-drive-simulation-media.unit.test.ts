import { describe, expect, it } from "vitest";

import {
  callDrive,
  capabilitiesOf,
  createSimulation,
  fileNames,
  idOf,
  jsonBody,
  listedFiles,
  reasonOf,
} from "./google-drive-simulation-harness";

import type { GoogleDriveSimulation } from "@/backend/google/GoogleDriveSimulation";

async function download(
  simulation: GoogleDriveSimulation,
  id: string,
): ReturnType<typeof callDrive> {
  return callDrive(simulation, `/drive/v3/files/${id}`, {
    query: { alt: "media" },
  });
}

async function exportAs(
  simulation: GoogleDriveSimulation,
  id: string,
  mimeType: string,
): ReturnType<typeof callDrive> {
  return callDrive(simulation, `/drive/v3/files/${id}/export`, {
    query: { mimeType },
  });
}

describe("GoogleDriveSimulation downloads", () => {
  it("downloads the bytes of a binary file", async () => {
    const answer = await download(createSimulation(), "sim-readme");

    expect(await answer.response.text()).toBe("Pages Simulation\n");
    expect(answer.response.headers.get("Content-Type")).toBe("text/plain");
    expect(answer.response.headers.get("Content-Length")).toBe("17");
  });

  it("downloads an empty body for a file without content", async () => {
    const simulation = createSimulation();
    const created = await callDrive(simulation, "/drive/v3/files", {
      body: jsonBody({ name: "leer.bin" }),
      method: "POST",
    });
    const answer = await download(simulation, idOf(created));

    expect(answer.status).toBe(200);
    expect(answer.response.headers.get("Content-Length")).toBe("0");
    expect((await answer.response.arrayBuffer()).byteLength).toBe(0);
  });

  it("refuses to download folders and Google documents", async () => {
    const simulation = createSimulation();

    for (const id of ["sim-projects", "sim-concept-doc"]) {
      const answer = await download(simulation, id);

      expect(answer.status).toBe(403);
      expect(reasonOf(answer)).toBe("fileNotDownloadable");
    }
  });

  it("streams a large file as generated bytes", async () => {
    const answer = await download(createSimulation(), "sim-large-video");
    const reader = answer.response.body?.getReader();
    const first = await reader?.read();

    expect(answer.response.headers.get("Content-Length")).toBe(
      String(300 * 1024 * 1024),
    );
    expect(first?.value?.length).toBe(64 * 1024);
    expect(first?.value?.[0]).toBe(0x53);
    await reader?.cancel();
  });
});

describe("GoogleDriveSimulation exports", () => {
  it("exports a document as plain text and as HTML", async () => {
    const simulation = createSimulation();
    const plain = await exportAs(simulation, "sim-concept-doc", "text/plain");
    const html = await exportAs(simulation, "sim-concept-doc", "text/html");

    expect(await plain.response.text()).toContain("Konzept für Pages Storage");
    expect(plain.response.headers.get("Content-Type")).toBe("text/plain");
    expect(await html.response.text()).toMatch(
      /^<html><body><pre>.*<\/pre><\/body><\/html>$/su,
    );
  });

  it("exports a spreadsheet as CSV and a document as a simulated PDF", async () => {
    const simulation = createSimulation();
    const csv = await exportAs(simulation, "sim-budget-sheet", "text/csv");
    const pdf = await exportAs(
      simulation,
      "sim-concept-doc",
      "application/pdf",
    );

    expect(await csv.response.text()).toBe(
      "Posten,Betrag\nServer,120\nLizenzen,80",
    );
    expect(await pdf.response.text()).toBe(
      "SIMULATION: Konzept exported as application/pdf\n",
    );
  });

  it("exports a drawing as SVG carrying its name", async () => {
    const drawing = await exportAs(
      createSimulation(),
      "sim-type-drawing",
      "image/svg+xml",
    );

    expect(await drawing.response.text()).toBe(
      '<svg xmlns="http://www.w3.org/2000/svg"><text>Skizze</text></svg>',
    );
  });

  it("refuses an unsupported or missing export format", async () => {
    const simulation = createSimulation();
    const badFormat = await exportAs(simulation, "sim-concept-doc", "text/csv");
    const noFormat = await callDrive(
      simulation,
      "/drive/v3/files/sim-concept-doc/export",
    );

    expect(badFormat.status).toBe(400);
    expect(reasonOf(badFormat)).toBe("badRequest");
    expect(noFormat.status).toBe(400);
  });

  it("refuses to export a file that is no Google document", async () => {
    const answer = await exportAs(
      createSimulation(),
      "sim-readme",
      "text/plain",
    );

    expect(answer.status).toBe(403);
    expect(reasonOf(answer)).toBe("fileNotExportable");
  });
});

describe("GoogleDriveSimulation item_forbidden scenario", () => {
  it("locks entries named gesperrt* for every kind of access", async () => {
    const simulation = createSimulation("item_forbidden");
    const requests = [
      ["/drive/v3/files/sim-locked-file", "GET"],
      ["/drive/v3/files/sim-locked-folder", "GET"],
      ["/drive/v3/files/sim-locked-file/export", "GET"],
      ["/drive/v3/files/sim-locked-file/copy", "POST"],
    ];

    for (const [path, method] of requests) {
      const answer = await callDrive(simulation, path ?? "", { method });

      expect(answer.status).toBe(403);
      expect(reasonOf(answer)).toBe("insufficientFilePermissions");
    }
  });

  it("shows locked entries as not editable and others as editable", async () => {
    const simulation = createSimulation("item_forbidden");
    const listed = await callDrive(simulation, "/drive/v3/files", {
      query: { q: "name contains 'gesperrt'" },
    });
    const open = await callDrive(simulation, "/drive/v3/files/sim-root-note");

    expect(fileNames(listed)).toEqual([
      "gesperrt-Ordner",
      "gesperrt-vertraulich.txt",
    ]);
    expect(
      listedFiles(listed).map((file) => file.capabilities["canEdit"]),
    ).toEqual([false, false]);
    expect(capabilitiesOf(open)["canEdit"]).toBe(true);
  });

  it("refuses to create or move below a locked folder", async () => {
    const simulation = createSimulation("item_forbidden");
    const created = await callDrive(simulation, "/drive/v3/files", {
      body: jsonBody({ name: "x", parents: ["sim-locked-folder"] }),
      method: "POST",
    });
    const moved = await callDrive(simulation, "/drive/v3/files/sim-root-note", {
      body: "{}",
      method: "PATCH",
      query: { addParents: "sim-locked-folder", removeParents: "sim-root" },
    });

    expect(created.status).toBe(403);
    expect(moved.status).toBe(403);
  });

  it("matches the lock name case-insensitively", async () => {
    const simulation = createSimulation("item_forbidden");
    const created = await callDrive(simulation, "/drive/v3/files", {
      body: jsonBody({ name: "GESPERRT neu" }),
      method: "POST",
    });
    const reopened = await callDrive(
      simulation,
      `/drive/v3/files/${idOf(created)}`,
    );

    expect(created.status).toBe(200);
    expect(capabilitiesOf(created)["canEdit"]).toBe(false);
    expect(reopened.status).toBe(403);
  });
});
