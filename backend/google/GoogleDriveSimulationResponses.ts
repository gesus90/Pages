import type { SimulatedFile } from "@/backend/google/GoogleDriveSimulationSeed";

/** Bytes per generated chunk of a large simulated file. */
const CHUNK_BYTES = 64 * 1024;

/** An upload as the simulation reads it. */
export interface SimulatedUpload {
  readonly metadata: Record<string, unknown>;
  readonly content: Buffer;
  readonly contentType: string;
}

/**
 * Builds a refusal in Drive's error format.
 *
 * @param status - HTTP status.
 * @param reason - Drive's `reason`, which the clients translate.
 * @param message - Drive's human-readable message.
 * @returns The answer.
 */
export function simulatedError(
  status: number,
  reason: string,
  message: string,
): Response {
  return Response.json(
    {
      error: {
        code: status,
        errors: [{ domain: "global", message, reason }],
        message,
      },
    },
    { status },
  );
}

function exportText(file: SimulatedFile, mimeType: string): string {
  const text = file.content?.toString("utf8") ?? "";

  if (mimeType === "text/html") {
    return `<html><body><pre>${text.replace(/[<>&]/gu, " ")}</pre></body></html>`;
  }

  if (mimeType.startsWith("text/") || mimeType === "image/svg+xml") {
    return mimeType === "image/svg+xml"
      ? `<svg xmlns="http://www.w3.org/2000/svg"><text>${file.name}</text></svg>`
      : text;
  }

  return `SIMULATION: ${file.name} exported as ${mimeType}\n`;
}

function generatedStream(size: number): ReadableStream<Uint8Array> {
  let sent = 0;

  return new ReadableStream<Uint8Array>({
    pull(controller): void {
      if (sent >= size) {
        controller.close();

        return;
      }

      const length = Math.min(CHUNK_BYTES, size - sent);

      controller.enqueue(new Uint8Array(length).fill(0x53));
      sent += length;
    },
  });
}

/**
 * Builds the bytes of a download or an export.
 *
 * @param file - The simulated entry.
 * @param mimeType - The type of the answer; for an export the chosen format.
 * @returns The answer; a large file streams generated bytes instead of holding them.
 */
export function simulatedMedia(
  file: SimulatedFile,
  mimeType: string,
): Response {
  if (file.virtualSize !== null) {
    return new Response(generatedStream(file.virtualSize), {
      headers: {
        "Content-Length": String(file.virtualSize),
        "Content-Type": mimeType,
      },
    });
  }

  const bytes =
    mimeType === file.mimeType
      ? (file.content ?? Buffer.alloc(0))
      : Buffer.from(exportText(file, mimeType), "utf8");

  return new Response(new Uint8Array(bytes), {
    headers: {
      "Content-Length": String(bytes.length),
      "Content-Type": mimeType,
    },
  });
}

function headerValue(init: RequestInit, name: string): string {
  return new Headers(init.headers).get(name) ?? "";
}

function readMetadata(text: string): Record<string, unknown> | null {
  try {
    const parsed: unknown = JSON.parse(text);

    return typeof parsed === "object" &&
      parsed !== null &&
      !Array.isArray(parsed)
      ? { ...parsed }
      : null;
  } catch {
    // An unreadable metadata part makes the whole upload unreadable.
    return null;
  }
}

function readParts(body: Buffer, boundary: string): Buffer[] {
  const delimiter = Buffer.from(`--${boundary}`);
  const parts: Buffer[] = [];
  let start = body.indexOf(delimiter);

  while (start !== -1) {
    const next = body.indexOf(delimiter, start + delimiter.length);

    if (next === -1) {
      break;
    }

    parts.push(body.subarray(start + delimiter.length, next));
    start = next;
  }

  return parts;
}

function splitPart(
  part: Buffer,
): { readonly headers: string; readonly content: Buffer } | null {
  const separator = part.indexOf("\r\n\r\n");

  if (separator === -1) {
    return null;
  }

  // The part starts after the boundary line break and ends before the next one.
  const content = part.subarray(separator + 4, part.length - 2);

  return { content, headers: part.subarray(0, separator).toString("utf8") };
}

function readMultipart(
  body: Buffer,
  contentType: string,
): SimulatedUpload | null {
  const boundary = /boundary=([^;]+)/u.exec(contentType)?.[1]?.trim();

  if (boundary === undefined) {
    return null;
  }

  const [metadataPart, mediaPart] = readParts(body, boundary).map(splitPart);

  if (!metadataPart || !mediaPart) {
    return null;
  }

  const metadata = readMetadata(metadataPart.content.toString("utf8"));
  const mediaType =
    /content-type:\s*([^\r\n]+)/iu.exec(mediaPart.headers)?.[1]?.trim() ??
    "application/octet-stream";

  return metadata
    ? {
        content: Buffer.from(mediaPart.content),
        contentType: mediaType,
        metadata,
      }
    : null;
}

/**
 * Reads an upload of type `media` or `multipart`.
 *
 * @param url - The upload address with `uploadType`.
 * @param init - The request with its body.
 * @returns Metadata and bytes, or `null` for an unreadable upload.
 */
export async function readSimulatedUpload(
  url: URL,
  init: RequestInit,
): Promise<SimulatedUpload | null> {
  const body = Buffer.from(await new Response(init.body ?? null).arrayBuffer());
  const contentType = headerValue(init, "Content-Type");
  const uploadType = url.searchParams.get("uploadType");

  if (uploadType === "media") {
    return {
      content: body,
      contentType: contentType || "application/octet-stream",
      metadata: {},
    };
  }

  return uploadType === "multipart" ? readMultipart(body, contentType) : null;
}
